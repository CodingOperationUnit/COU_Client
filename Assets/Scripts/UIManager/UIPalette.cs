    };

    private static readonly Color[] light =
    {
        new Color32(0xDE, 0xE4, 0xEB, 0xFF),
        new Color32(0xF1, 0xF3, 0xF5, 0xFF),
        new Color32(0xFF, 0xFF, 0xFF, 0xFF),
        new Color32(0xC9, 0xD3, 0xDF, 0xFF),
